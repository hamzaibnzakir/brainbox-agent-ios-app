#!/usr/bin/env python3
"""Embeds setup-vps.sh in the phone and PC apps (Copy setup script). Run after editing the script;
CI fails if the embedded copies are stale (scripts/tailscale/embed.py --check)."""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parents[2]
script = (root / "scripts/tailscale/setup-vps.sh").read_text()
swift = ('// Generated by scripts/tailscale/embed.py from scripts/tailscale/setup-vps.sh — do not edit.\n'
         'enum TailscaleSetup {\n    static let script = #"""\n' + script + '"""#\n}\n')
ts = ('// Generated by scripts/tailscale/embed.py from scripts/tailscale/setup-vps.sh — do not edit.\n'
      'export const TAILSCALE_SETUP_SCRIPT = ' + json.dumps(script) + ';\n')
targets = {root / "BrainboxAgent/Features/Connect/TailscaleSetup.swift": swift,
           root / "desktop/src/shared/tailscaleSetup.ts": ts}
stale = [str(p) for p, text in targets.items() if not p.exists() or p.read_text() != text]
if "--check" in sys.argv:
    if stale: sys.exit("stale embedded setup script: " + ", ".join(stale) + " — run scripts/tailscale/embed.py")
    sys.exit(0)
for p, text in targets.items(): p.write_text(text)
print("embedded into", len(targets), "files")
